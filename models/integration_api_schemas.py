"""Validated request/transport schemas for the integration API context."""

from typing import Literal

from pydantic import BaseModel, Field, field_validator

from .turn_api_schemas import ClarificationIn, ManualRollIn


class SillyTavernManualRollIn(ManualRollIn):
    query: str = Field(..., min_length=1, max_length=10000)
    answer_external_turn_id: str = Field(..., min_length=1, max_length=500)

    @field_validator("query", "answer_external_turn_id")
    @classmethod
    def validate_manual_roll_text(cls, value: str) -> str:
        value = value.strip()
        if not value:
            raise ValueError("text must not be empty")
        return value


class SillyTavernClarificationIn(ClarificationIn):
    query: str = Field(..., min_length=1, max_length=10000)
    answer_external_turn_id: str = Field(..., min_length=1, max_length=500)

    @field_validator("answer_external_turn_id")
    @classmethod
    def validate_answer_external_turn_id(cls, value: str) -> str:
        value = value.strip()
        if not value:
            raise ValueError("answer_external_turn_id must not be empty")
        return value

    @field_validator("query")
    @classmethod
    def validate_query(cls, value: str) -> str:
        value = value.strip()
        if not value:
            raise ValueError("query must not be empty")
        return value


class SillyTavernContextIn(BaseModel):
    """
    Petición de contexto procedente de SillyTavern.

    query representa la acción o situación actual que el
    modelo va a utilizar para determinar qué recuerdos del
    mundo son relevantes.
    """

    query: str = Field(
        ...,
        min_length=1,
        max_length=10000,
    )

    @field_validator("query")
    @classmethod
    def validate_query(
        cls,
        value: str,
    ) -> str:
        value = value.strip()

        if not value:
            raise ValueError(
                "query must not be empty"
            )

        return value


class SillyTavernTurnResolveIn(BaseModel):
    """Player intent and stable identity submitted before SillyTavern narration."""

    player_input: str = Field(..., min_length=1, max_length=10000)
    external_turn_id: str = Field(..., min_length=1, max_length=500)
    query: str = Field(..., min_length=1, max_length=10000)
    dice_mode: Literal["automatic", "manual"] = "automatic"

    @field_validator("player_input", "external_turn_id", "query")
    @classmethod
    def validate_required_text(cls, value: str) -> str:
        value = value.strip()
        if not value:
            raise ValueError("text must not be empty")
        return value


class SillyTavernTurnCompleteIn(BaseModel):
    """
    Narrative generated by the external client after durable resolution.
    """

    player_input: str = Field(
        ...,
        min_length=1,
        max_length=10000,
    )

    narrative: str = Field(
        ...,
        min_length=1,
        max_length=30000,
    )

    external_turn_id: str = Field(
        ...,
        min_length=1,
        max_length=500,
    )

    turn_version: int = Field(
        default=1,
        ge=1,
    )

    @field_validator(
        "player_input",
        "narrative",
    )
    @classmethod
    def validate_text(
        cls,
        value: str,
    ) -> str:
        value = value.strip()

        if not value:
            raise ValueError(
                "text must not be empty"
            )

        return value

    @field_validator("external_turn_id")
    @classmethod
    def validate_external_turn_id(cls, value: str) -> str:
        value = value.strip()
        if not value:
            raise ValueError("external_turn_id must not be empty")
        return value
